-- Run in the Supabase SQL Editor to enable customer detail cash in/out (create, read, update, delete).
-- These rows belong only to the customer ledger; cashbook and exchange wallets are untouched.
-- Rows are linked to a customer only; access is validated through customer_id.
-- Safe to re-run. If the table is ever dropped and recreated, run this again:
-- dropping a table also drops its policies, and RLS without policies denies every request.
create table if not exists public.customer_ledger_transactions (
  id bigint generated by default as identity not null,
  customer_id bigint not null,
  type text not null,
  amount numeric(20, 6) not null,
  currency text not null,
  transaction_date date not null default current_date,
  memo text null,
  serial_no text null,
  created_at timestamp with time zone not null default now(),
  constraint customer_ledger_transactions_pkey primary key (id),
  constraint customer_ledger_transactions_customer_id_fkey foreign key (customer_id) references public.customers (id) on delete cascade,
  constraint customer_ledger_transactions_amount_check check (amount > 0),
  constraint customer_ledger_transactions_type_check check (type = any (array['cash_in'::text, 'cash_out'::text]))
);

create index if not exists customer_ledger_transactions_customer_idx
  on public.customer_ledger_transactions using btree (customer_id);

-- The primary key is also the sequential voucher number shown in the feed.
update public.customer_ledger_transactions
set serial_no = id::text
where serial_no is null or serial_no = '';

create or replace function public.set_customer_ledger_serial_no()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.serial_no := new.id::text;
  return new;
end;
$$;

drop trigger if exists customer_ledger_transactions_set_serial_no
  on public.customer_ledger_transactions;
create trigger customer_ledger_transactions_set_serial_no
  before insert or update on public.customer_ledger_transactions
  for each row execute function public.set_customer_ledger_serial_no();

alter table public.customer_ledger_transactions enable row level security;
grant select, insert, update, delete on public.customer_ledger_transactions to authenticated;
grant usage, select on sequence public.customer_ledger_transactions_id_seq to authenticated;

drop policy if exists customer_ledger_transactions_select_owned on public.customer_ledger_transactions;
drop policy if exists customer_ledger_transactions_insert_owned on public.customer_ledger_transactions;
drop policy if exists customer_ledger_transactions_update_owned on public.customer_ledger_transactions;
drop policy if exists customer_ledger_transactions_delete_owned on public.customer_ledger_transactions;

drop function if exists public.customer_ledger_can_access(bigint, bigint);
drop function if exists public.customer_ledger_user_owns_business(bigint);
drop function if exists public.customer_ledger_customer_belongs_to_business(bigint, bigint);

-- A row is accessible when its customer is visible to the signed-in user.
-- The customers table's own RLS decides which customers that is.
create policy customer_ledger_transactions_select_owned
  on public.customer_ledger_transactions for select to authenticated
  using (exists (
    select 1 from public.customers as customer
    where customer.id = customer_ledger_transactions.customer_id
  ));

create policy customer_ledger_transactions_insert_owned
  on public.customer_ledger_transactions for insert to authenticated
  with check (exists (
    select 1 from public.customers as customer
    where customer.id = customer_ledger_transactions.customer_id
  ));

create policy customer_ledger_transactions_update_owned
  on public.customer_ledger_transactions for update to authenticated
  using (exists (
    select 1 from public.customers as customer
    where customer.id = customer_ledger_transactions.customer_id
  ))
  with check (exists (
    select 1 from public.customers as customer
    where customer.id = customer_ledger_transactions.customer_id
  ));

create policy customer_ledger_transactions_delete_owned
  on public.customer_ledger_transactions for delete to authenticated
  using (exists (
    select 1 from public.customers as customer
    where customer.id = customer_ledger_transactions.customer_id
  ));

notify pgrst, 'reload schema';
