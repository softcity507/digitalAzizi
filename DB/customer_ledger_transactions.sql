create table public.customer_ledger_transactions (
  id bigint generated by default as identity not null,
  customer_id bigint not null,
  type text not null,
  amount numeric(20, 6) not null,
  currency text not null,
  transaction_date date not null default CURRENT_DATE,
  memo text null,
  serial_no text null,
  created_at timestamp with time zone not null default now(),
  constraint customer_ledger_transactions_pkey primary key (id),
  constraint customer_ledger_transactions_customer_id_fkey foreign KEY (customer_id) references customers (id) on delete CASCADE,
  constraint customer_ledger_transactions_amount_check check ((amount > (0)::numeric)),
  constraint customer_ledger_transactions_type_check check (
    (
      type = any (array['cash_in'::text, 'cash_out'::text])
    )
  )
) TABLESPACE pg_default;

create index IF not exists customer_ledger_transactions_customer_idx on public.customer_ledger_transactions using btree (customer_id) TABLESPACE pg_default;