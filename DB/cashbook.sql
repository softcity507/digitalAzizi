create table public.cashbook (
  id bigint generated by default as identity not null,
  business_id bigint null,
  customer_id bigint null,
  from_customer_id bigint null,
  to_customer_id bigint null,
  type text not null,
  currency character varying(10) not null,
  amount numeric(15, 4) not null,
  mode character varying(50) null,
  transaction_date timestamp with time zone not null default now(),
  description text null,
  from_currency character varying(10) null,
  to_currency character varying(10) null,
  from_amount numeric(15, 4) null,
  to_amount numeric(15, 4) null,
  exchange_rate numeric(15, 6) null,
  details jsonb null,
  created_at timestamp with time zone not null default now(),
  constraint cashbook_pkey primary key (id),
  constraint cashbook_business_id_fkey foreign KEY (business_id) references businesses (id) on delete CASCADE,
  constraint cashbook_customer_fkey foreign KEY (customer_id) references customers (id) on delete set null,
  constraint cashbook_from_customer_fkey foreign KEY (from_customer_id) references customers (id) on delete set null,
  constraint cashbook_to_customer_fkey foreign KEY (to_customer_id) references customers (id) on delete set null
) TABLESPACE pg_default;